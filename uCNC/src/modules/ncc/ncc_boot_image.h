#ifndef NCC_BOOT_IMAGE_H
#define NCC_BOOT_IMAGE_H

#include <stdint.h>

/* The boot picture (logo.bmp): its own sixteen colours and the rows that
   use them. Generated by `tools/boot_image.py` from the picture beside
   it - change the picture and run the tool, never this. The colours are
   taken from the renderer's palette when the splash starts and given
   back when it ends (`ncc_boot_release()`), so the panel's own colours
   are the panel's own again by the time it draws. */
#define NCC_BOOT_IMAGE_W 600
#define NCC_BOOT_IMAGE_H 399
#define NCC_BOOT_IMAGE_X 0
#define NCC_BOOT_IMAGE_Y 200
#define NCC_BOOT_IMAGE_COLOURS 15
/* The picture is centred on the panel's black; this is the colour the
   letterbox is painted in. */
#define NCC_BOOT_IMAGE_BG 0

typedef struct {
    uint8_t r;
    uint8_t g;
    uint8_t b;
} ncc_boot_colour_t;

extern const ncc_boot_colour_t ncc_boot_image_colours[NCC_BOOT_IMAGE_COLOURS];
/* index, count, ... */
extern const uint16_t ncc_boot_image_runs[];
extern const uint32_t ncc_boot_image_run_count;

#endif
